//! Toolkit-independent keyboard and pointer events.

use std::time::{Duration, Instant};

/// A key, reduced to what the suite's interfaces act on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Key {
    Escape,
    Enter,
    Tab,
    Backspace,
    Delete,
    Up,
    Down,
    Left,
    Right,
    Home,
    End,
    PageUp,
    PageDown,
    Insert,
    /// The context-menu key.
    Menu,
    /// A function key, `F(1)` to `F(12)`.
    F(u8),
    /// A printable character, as produced by the active layout.
    Char(char),
    /// Anything else (modifiers, function keys, …).
    Other,
}

/// Modifier keys held during an event.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Mods {
    pub ctrl: bool,
    pub alt: bool,
    pub shift: bool,
    pub logo: bool,
    /// Caps Lock is on. Not a shortcut modifier: it only changes letters.
    pub caps_lock: bool,
}

impl Mods {
    /// No modifier that turns a keypress into a shortcut is held.
    pub fn is_plain(&self) -> bool {
        !(self.ctrl || self.alt || self.logo)
    }
}

/// A key press (or auto-repeat of one).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyEvent {
    pub key: Key,
    pub mods: Mods,
    /// Generated by holding the key down.
    pub repeat: bool,
}

/// Direction of a list-navigation keypress.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Nav {
    Up,
    Down,
}

impl KeyEvent {
    /// The suite-wide list navigation keys: arrows, `Ctrl+n`/`Ctrl+p`, and —
    /// when `letters` is set, i.e. no text field has focus — `j`/`k`.
    pub fn nav(&self, letters: bool) -> Option<Nav> {
        match self.key {
            Key::Up => Some(Nav::Up),
            Key::Down => Some(Nav::Down),
            Key::Char('p') if self.mods.ctrl => Some(Nav::Up),
            Key::Char('n') if self.mods.ctrl => Some(Nav::Down),
            Key::Char('k') if letters && self.mods.is_plain() => Some(Nav::Up),
            Key::Char('j') if letters && self.mods.is_plain() => Some(Nav::Down),
            _ => None,
        }
    }

    /// The character to insert into a text field, if this is plain typing.
    pub fn text(&self) -> Option<char> {
        match self.key {
            Key::Char(c) if self.mods.is_plain() => Some(c),
            _ => None,
        }
    }
}

/// Mouse buttons.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Button {
    Left,
    Right,
    Middle,
    Other(u32),
}

/// A pointer event in surface-local logical pixels.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PointerEvent {
    Enter {
        x: f32,
        y: f32,
    },
    Leave,
    Move {
        x: f32,
        y: f32,
    },
    Press {
        x: f32,
        y: f32,
        button: Button,
    },
    Release {
        x: f32,
        y: f32,
        button: Button,
    },
    /// Scroll deltas in logical pixels; positive `dy` scrolls content down.
    Scroll {
        x: f32,
        y: f32,
        dx: f32,
        dy: f32,
        /// From a mouse wheel, which moves in notches, rather than a
        /// touchpad, which glides: lists step by rows for the one and
        /// follow the fingers for the other.
        wheel: bool,
    },
}

/// The side buttons most mice have, which browsers and file managers use
/// for back and forward (evdev's `BTN_SIDE` and `BTN_EXTRA`).
pub const BUTTON_BACK: Button = Button::Other(0x113);
pub const BUTTON_FORWARD: Button = Button::Other(0x114);

/// Counts clicks: the second press of a double-click, the third of a
/// triple. A press counts on from the one before if it is the same button,
/// soon enough, and near enough; otherwise it is a first click.
#[derive(Clone, Copy, Debug)]
pub struct Clicks {
    last: Option<(Instant, f32, f32, Button, u8)>,
    /// Longest gap between the clicks of a double-click.
    pub interval: Duration,
    /// How far the pointer may wander between them, in logical pixels.
    pub slop: f32,
}

impl Default for Clicks {
    fn default() -> Self {
        Self {
            last: None,
            // GTK's and libinput's usual.
            interval: Duration::from_millis(400),
            slop: 4.0,
        }
    }
}

impl Clicks {
    /// Take a press and say which click it is: 1, 2, 3, … .
    pub fn press(&mut self, x: f32, y: f32, button: Button, now: Instant) -> u8 {
        let count = match self.last {
            Some((at, last_x, last_y, last_button, count))
                if last_button == button
                    && now.saturating_duration_since(at) <= self.interval
                    && (x - last_x).abs() <= self.slop
                    && (y - last_y).abs() <= self.slop =>
            {
                count.saturating_add(1)
            }
            _ => 1,
        };
        self.last = Some((now, x, y, button, count));
        count
    }

    /// Forget the last click, so the next press is a first one (after a
    /// drag, say, or once the thing clicked has gone).
    pub fn reset(&mut self) {
        self.last = None;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn key(key: Key, ctrl: bool) -> KeyEvent {
        KeyEvent {
            key,
            mods: Mods {
                ctrl,
                ..Mods::default()
            },
            repeat: false,
        }
    }

    #[test]
    fn clicks_count_up_while_quick_and_close() {
        let mut clicks = Clicks::default();
        let start = Instant::now();
        let at = |ms| start + Duration::from_millis(ms);
        assert_eq!(clicks.press(10.0, 10.0, Button::Left, at(0)), 1);
        assert_eq!(clicks.press(11.0, 12.0, Button::Left, at(200)), 2);
        assert_eq!(clicks.press(11.0, 12.0, Button::Left, at(400)), 3);
        // Too slow.
        assert_eq!(clicks.press(11.0, 12.0, Button::Left, at(1000)), 1);
        // Too far.
        assert_eq!(clicks.press(40.0, 12.0, Button::Left, at(1100)), 1);
        // Another button.
        assert_eq!(clicks.press(40.0, 12.0, Button::Right, at(1200)), 1);
        clicks.reset();
        assert_eq!(clicks.press(40.0, 12.0, Button::Right, at(1300)), 1);
    }

    #[test]
    fn navigation_keys() {
        assert_eq!(key(Key::Down, false).nav(false), Some(Nav::Down));
        assert_eq!(key(Key::Char('n'), true).nav(false), Some(Nav::Down));
        assert_eq!(key(Key::Char('p'), true).nav(false), Some(Nav::Up));
        assert_eq!(key(Key::Char('j'), false).nav(true), Some(Nav::Down));
        assert_eq!(key(Key::Char('k'), false).nav(true), Some(Nav::Up));
        // In a text field `j`/`k` are just letters.
        assert_eq!(key(Key::Char('j'), false).nav(false), None);
        assert_eq!(key(Key::Char('j'), false).text(), Some('j'));
        assert_eq!(key(Key::Char('n'), true).text(), None);
    }
}

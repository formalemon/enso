//! Toolkit-independent keyboard and pointer events.

/// A key, reduced to what the suite's interfaces act on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Key {
    Escape,
    Enter,
    Tab,
    Backspace,
    Delete,
    Up,
    Down,
    Left,
    Right,
    Home,
    End,
    PageUp,
    PageDown,
    /// A printable character, as produced by the active layout.
    Char(char),
    /// Anything else (modifiers, function keys, …).
    Other,
}

/// Modifier keys held during an event.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Mods {
    pub ctrl: bool,
    pub alt: bool,
    pub shift: bool,
    pub logo: bool,
}

impl Mods {
    /// No modifier that turns a keypress into a shortcut is held.
    pub fn is_plain(&self) -> bool {
        !(self.ctrl || self.alt || self.logo)
    }
}

/// A key press (or auto-repeat of one).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyEvent {
    pub key: Key,
    pub mods: Mods,
    /// Generated by holding the key down.
    pub repeat: bool,
}

/// Direction of a list-navigation keypress.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Nav {
    Up,
    Down,
}

impl KeyEvent {
    /// The suite-wide list navigation keys: arrows, `Ctrl+n`/`Ctrl+p`, and —
    /// when `letters` is set, i.e. no text field has focus — `j`/`k`.
    pub fn nav(&self, letters: bool) -> Option<Nav> {
        match self.key {
            Key::Up => Some(Nav::Up),
            Key::Down => Some(Nav::Down),
            Key::Char('p') if self.mods.ctrl => Some(Nav::Up),
            Key::Char('n') if self.mods.ctrl => Some(Nav::Down),
            Key::Char('k') if letters && self.mods.is_plain() => Some(Nav::Up),
            Key::Char('j') if letters && self.mods.is_plain() => Some(Nav::Down),
            _ => None,
        }
    }

    /// The character to insert into a text field, if this is plain typing.
    pub fn text(&self) -> Option<char> {
        match self.key {
            Key::Char(c) if self.mods.is_plain() => Some(c),
            _ => None,
        }
    }
}

/// Mouse buttons.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Button {
    Left,
    Right,
    Middle,
    Other(u32),
}

/// A pointer event in surface-local logical pixels.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PointerEvent {
    Enter {
        x: f32,
        y: f32,
    },
    Leave,
    Move {
        x: f32,
        y: f32,
    },
    Press {
        x: f32,
        y: f32,
        button: Button,
    },
    Release {
        x: f32,
        y: f32,
        button: Button,
    },
    /// Scroll deltas in logical pixels; positive `dy` scrolls content down.
    Scroll {
        x: f32,
        y: f32,
        dx: f32,
        dy: f32,
    },
}

#[cfg(test)]
mod tests {
    use super::*;

    fn key(key: Key, ctrl: bool) -> KeyEvent {
        KeyEvent {
            key,
            mods: Mods {
                ctrl,
                ..Mods::default()
            },
            repeat: false,
        }
    }

    #[test]
    fn navigation_keys() {
        assert_eq!(key(Key::Down, false).nav(false), Some(Nav::Down));
        assert_eq!(key(Key::Char('n'), true).nav(false), Some(Nav::Down));
        assert_eq!(key(Key::Char('p'), true).nav(false), Some(Nav::Up));
        assert_eq!(key(Key::Char('j'), false).nav(true), Some(Nav::Down));
        assert_eq!(key(Key::Char('k'), false).nav(true), Some(Nav::Up));
        // In a text field `j`/`k` are just letters.
        assert_eq!(key(Key::Char('j'), false).nav(false), None);
        assert_eq!(key(Key::Char('j'), false).text(), Some('j'));
        assert_eq!(key(Key::Char('n'), true).text(), None);
    }
}
